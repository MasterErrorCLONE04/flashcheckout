export type SpecificNicheKey =
  | 'cafe'
  | 'moda'
  | 'streetwear'
  | 'belleza'
  | 'joyeria'
  | 'tecnologia'
  | 'comida'
  | 'hogar'
  | 'mascotas'
  | 'deportes'
  | 'otros'

export function detectNicheFromPrompt(text?: string | null): SpecificNicheKey {
  const t = (text || '').toLowerCase()
  if (/(cafe|café|coffee|tueste|origen|grano|barista|prensa|filtrado)/.test(t)) return 'cafe'
  if (/(streetwear|urbano|hoodie|oversize|sneaker|calle|y2k)/.test(t)) return 'streetwear'
  if (/(joya|joyer|oro|plata|anillo|collar|reloj|diamante|aretes|pulsera)/.test(t)) return 'joyeria'
  if (/(skincare|belleza|piel|botanic|facial|cosmet|crema|suero|serum|labial)/.test(t)) return 'belleza'
  if (/(tecno|gadget|audio|audifono|celular|iphone|gamer|setup|smartwatch)/.test(t)) return 'tecnologia'
  if (/(hamburgues|burger|pizza|restaurante|sabor|torta|alitas|gourmet)/.test(t)) return 'comida'
  if (/(hogar|mueble|decor|vela|sabana|vajilla|ceramica|lampara|planta)/.test(t)) return 'hogar'
  if (/(mascota|perro|gato|veterinar|cachorro|pet)/.test(t)) return 'mascotas'
  if (/(deporte|fitness|gym|gimnasio|suplemento|proteina|crossfit|running)/.test(t)) return 'deportes'
  if (/(ropa|vestido|camis|calzado|zapato|boutique|moda)/.test(t)) return 'moda'
  return 'cafe'
}

