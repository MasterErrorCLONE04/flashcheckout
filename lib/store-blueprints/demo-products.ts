export function getDemoPreviewProducts(
  category?: string | null,
  bio?: string | null,
  prompt?: string | null
): Product[] {
  const combined = [prompt, bio, category].filter(Boolean).join('. ')
  const nicheKey = detectNicheFromPrompt(combined)
  const list = NICHE_DEMO_PRODUCTS[nicheKey] || NICHE_DEMO_PRODUCTS.cafe
  return list && list.length > 0 ? list : NICHE_DEMO_PRODUCTS.cafe
}
